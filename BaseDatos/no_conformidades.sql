/* ============================================================
   CALIDAD: INCIDENCIAS Y NO CONFORMIDADES
   Sustituye al Excel "INCIDENCIAS Y NO CONFORMIDADES - CALIDAD" (MT-RG09).
   Se ejecuta una vez, después de crear_tablas.sql.
