-- Opciones de los desplegables (la hoja LISTAS del Excel). Los registros guardan
-- el texto elegido, no el id: así cambiar o desactivar una opción no altera lo
-- que ya está registrado. Para quitar una opción de los desplegables: activo = 0.
CREATE TABLE CALIDAD_LISTA (
    id INT IDENTITY(1,1) PRIMARY KEY,
    lista NVARCHAR(20) NOT NULL,
    valor NVARCHAR(150) NOT NULL,
    descripcion NVARCHAR(100) NULL,   -- solo los orígenes I, R, A, P
    orden INT NOT NULL,
    activo BIT NOT NULL CONSTRAINT DF_calidad_lista_activo DEFAULT 1,
    CONSTRAINT UQ_calidad_lista UNIQUE (lista, valor),
    CONSTRAINT CK_calidad_lista CHECK (lista IN ('ORIGEN', 'SECCION', 'TIPO', 'PERSONA',
        'MC_PCC_BPM', 'PARAMETRO', 'OPERARIO', 'CAPITULO_NORMA'))
);

-- Una fila de la hoja INCIDENCIAS. El estado (en plazo, fuera de plazo, cerrada)
-- no se guarda: se calcula con la fecha prevista y la fecha fin, como en el Excel.
CREATE TABLE NO_CONFORMIDAD (
    id INT IDENTITY(1,1) PRIMARY KEY,
    tipo_registro NVARCHAR(10) NOT NULL,          -- NC, INCIDENCIA o MEJORA
    -- Lo pone la aplicación según la serie (558, AC-2026-1, AI-20/04/26-1; incidencias 1, 2...).
    -- Texto y sin UNIQUE: en el Excel hay otros formatos (LC25-06) y algún número repetido.
    numero NVARCHAR(30) NULL,
    fecha_detectado DATE NOT NULL,
    origen NVARCHAR(150) NULL,
    seccion NVARCHAR(150) NULL,
    tipo NVARCHAR(150) NULL,                      -- solo NC
    problema NVARCHAR(MAX) NOT NULL,
    descripcion_causa NVARCHAR(MAX) NULL,
    accion_inmediata NVARCHAR(MAX) NULL,
    responsable NVARCHAR(150) NULL,
    fecha_prevista DATE NULL,
    fecha_fin DATE NULL,
    cliente NVARCHAR(150) NULL,
    proveedor NVARCHAR(150) NULL,
    mc_pcc_bpm NVARCHAR(150) NULL,                -- solo incidencias
    parametro NVARCHAR(150) NULL,                 -- solo incidencias
    operario NVARCHAR(150) NULL,                  -- solo incidencias
    capitulo_norma NVARCHAR(150) NULL,
    analisis_causa_raiz NVARCHAR(MAX) NULL,
    accion_correctora NVARCHAR(MAX) NULL,
    responsable_accion_correctora NVARCHAR(150) NULL,
    coste_economico DECIMAL(10,2) NULL,
    horas_mano_obra DECIMAL(7,2) NULL,
    seguimiento NVARCHAR(MAX) NULL,
    creado_por INT NOT NULL,
    creado_en DATETIME2 NOT NULL CONSTRAINT DF_no_conformidad_creado DEFAULT SYSDATETIME(),
    CONSTRAINT CK_no_conformidad_tipo CHECK (tipo_registro IN ('NC', 'INCIDENCIA', 'MEJORA')),
    CONSTRAINT CK_no_conformidad_coste CHECK (coste_economico >= 0),
    CONSTRAINT CK_no_conformidad_horas CHECK (horas_mano_obra >= 0),
    CONSTRAINT FK_no_conformidad_usuario FOREIGN KEY (creado_por) REFERENCES USUARIO(id)
);

CREATE INDEX IX_no_conformidad_fecha ON NO_CONFORMIDAD (fecha_detectado);
GO

-- Historial: igual que los de devoluciones, con devolucion_id NULL.
-- Se consulta con tabla_afectada = 'NO_CONFORMIDAD' y registro_id.
CREATE OR ALTER TRIGGER TR_NO_CONFORMIDAD_HISTORIAL ON NO_CONFORMIDAD
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM inserted) AND NOT EXISTS (SELECT 1 FROM deleted) RETURN;

    DECLARE @usuario INT = CAST(SESSION_CONTEXT(N'usuario_id') AS INT);
    IF @usuario IS NULL
        THROW 50001, 'No se ha indicado el usuario que realiza el cambio (sp_set_session_context).', 1;

    INSERT INTO HISTORIAL_CAMBIOS
        (devolucion_id, usuario_id, tabla_afectada, registro_id, accion, valores_anteriores, valores_nuevos, transaccion_id)
    SELECT NULL, @usuario, 'NO_CONFORMIDAD', c.registro_id, c.accion, c.anteriores, c.nuevos, CURRENT_TRANSACTION_ID()
    FROM inserted i
    FULL OUTER JOIN deleted d ON d.id = i.id
    CROSS APPLY (SELECT
        COALESCE(i.id, d.id) AS registro_id,
        CASE WHEN i.id IS NULL THEN 'DELETE' WHEN d.id IS NULL THEN 'INSERT' ELSE 'UPDATE' END AS accion,
        CASE WHEN d.id IS NULL THEN NULL
             ELSE (SELECT d.* FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES) END AS anteriores,
        CASE WHEN i.id IS NULL THEN NULL
             ELSE (SELECT i.* FOR JSON PATH, WITHOUT_ARRAY_WRAPPER, INCLUDE_NULL_VALUES) END AS nuevos
    ) c
    WHERE c.accion <> 'UPDATE' OR c.anteriores <> c.nuevos;
END;
GO

